import type { ConversationItem } from "@easy-job/shared";

const IMAGE_TYPES = new Set(["image/png", "image/jpeg", "image/gif", "image/webp"]);

type Block = {
  type?: string;
  text?: string;
  name?: string;
  id?: string;
  input?: Record<string, unknown>;
  content?: unknown;
  is_error?: boolean;
  tool_use_id?: string;
  source?: { type?: string; media_type?: string; data?: string };
};

type ClaudeLine = {
  type?: string;
  isSidechain?: boolean;
  isMeta?: boolean;
  timestamp?: string;
  uuid?: string;
  message?: { role?: string; content?: string | Block[] };
};

export function parseClaudeLine(raw: string): ConversationItem[] {
  let line: ClaudeLine;
  try {
    line = JSON.parse(raw) as ClaudeLine;
  } catch {
    return [];
  }
  if (line.isSidechain || line.isMeta) return [];
  if (line.type !== "user" && line.type !== "assistant" && line.type !== "system") return [];
  const at = Date.parse(line.timestamp ?? "") || 0;
  const id = line.uuid ?? `${line.type}-${at}`;
  const content = line.message?.content;
  if (typeof content === "string") {
    if (line.type === "user") {
      const clean = cleanUserText(content);
      return clean ? [{ id, at, ...clean }] : [];
    }
    if (!content.trim()) return [];
    return [{ id, at, role: line.type === "assistant" ? "agent" : "system", text: content }];
  }
  if (!Array.isArray(content)) return [];
  const items: ConversationItem[] = [];
  for (const block of content) {
    if (!block || typeof block !== "object") continue;
    if (block.type === "thinking") continue;
    if (block.type === "text" && block.text?.trim()) {
      const clean = line.type === "assistant" ? { role: "agent" as const, text: block.text } : cleanUserText(block.text);
      if (clean) items.push({ id: `${id}-text-${items.length}`, at, ...clean });
    } else if (block.type === "tool_use" && block.name) {
      items.push({
        id: block.id ?? `${id}-tool-${items.length}`,
        at,
        role: "tool",
        tool: { name: block.name, summary: toolSummary(block), ok: undefined },
      });
    } else if (block.type === "tool_result") {
      items.push({
        id: block.tool_use_id ? `${block.tool_use_id}-result` : `${id}-result-${items.length}`,
        at,
        role: "tool",
        tool: {
          name: "result",
          summary: snippetOf(block.content),
          ok: block.is_error === undefined ? true : !block.is_error,
        },
        ...resultImages(block.content),
      });
    } else if (block.type === "image") {
      const image = imageOf(block);
      if (!image) continue;
      const last = items.at(-1);
      if (last && last.role !== "tool") {
        last.images = [...(last.images ?? []), image];
      } else {
        items.push({ id: `${id}-image-${items.length}`, at, role: line.type === "assistant" ? "agent" : "user", images: [image] });
      }
    }
  }
  return items;
}

export function parseClaudeTranscript(raw: string): ConversationItem[] {
  const items: ConversationItem[] = [];
  for (const line of raw.split("\n")) {
    if (!line.trim()) continue;
    items.push(...parseClaudeLine(line));
  }
  return mergeToolResults(items);
}

const tag = (text: string, name: string) => text.match(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`))?.[1]?.trim();

/**
 * Claude Code writes slash commands, `!` shell runs and harness notes into user lines as XML-ish wrappers.
 * Show them the way the terminal does: `/model opus`, `! ls`, output as a note; reminders and caveats not at all.
 */
export function cleanUserText(raw: string): { role: "user" | "system"; text: string } | null {
  let text = raw.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, "").trim();
  if (!text) return null;
  if (text.startsWith("Caveat: The messages below were generated by the user while running local commands")) return null;
  if (/^\[Request interrupted by user[^\]]*\]$/.test(text)) return { role: "system", text: "Interrupted" };
  const command = tag(text, "command-name");
  if (command !== undefined) {
    const args = tag(text, "command-args");
    return { role: "user", text: `${command.startsWith("/") ? command : `/${command}`}${args ? ` ${args}` : ""}` };
  }
  const shell = tag(text, "bash-input");
  if (shell !== undefined) return { role: "user", text: `! ${shell}` };
  const out = tag(text, "local-command-stdout") ?? tag(text, "bash-stdout");
  const err = tag(text, "local-command-stderr") ?? tag(text, "bash-stderr");
  if (out !== undefined || err !== undefined) {
    const body = [out, err].filter(Boolean).join("\n").trim();
    return body ? { role: "system", text: body } : null;
  }
  text = text.replace(/<\/?(command-message|command-contents)>/g, "").trim();
  return text ? { role: "user", text } : null;
}

function toolSummary(block: Block): string {
  const input = block.input ?? {};
  if (typeof input.command === "string") return input.command.split("\n")[0] ?? input.command;
  if (typeof input.description === "string") return input.description;
  const first = Object.values(input).find((value) => typeof value === "string");
  return typeof first === "string" ? first.slice(0, 120) : block.name ?? "tool";
}

function snippet(content: unknown): string {
  if (typeof content === "string") return content.replace(/\s+/g, " ").trim().slice(0, 160);
  return "";
}

/** Screenshots and image reads come back inside a tool result; keep them with the call. */
function resultImages(content: unknown): { images?: Array<{ mime: string; dataUrl: string }> } {
  if (!Array.isArray(content)) return {};
  const images = (content as Block[]).filter((block) => block?.type === "image").map(imageOf).filter((image): image is { mime: string; dataUrl: string } => !!image);
  return images.length ? { images } : {};
}

function snippetOf(content: unknown): string {
  if (!Array.isArray(content)) return snippet(content);
  return snippet((content as Block[]).filter((block) => block?.type === "text").map((block) => block.text ?? "").join(" "));
}

function imageOf(block: Block): { mime: string; dataUrl: string } | null {
  const mime = block.source?.media_type;
  const data = block.source?.data;
  if (!mime || !data || !IMAGE_TYPES.has(mime)) return null;
  return { mime, dataUrl: `data:${mime};base64,${data}` };
}

/** A tool_result line marks the matching tool call instead of standing alone. */
export function mergeToolResults(items: ConversationItem[]): ConversationItem[] {
  const tools = new Map<string, ConversationItem>();
  for (const item of items) {
    if (item.role === "tool" && item.tool && item.tool.name !== "result") tools.set(item.id, item);
  }
  const out: ConversationItem[] = [];
  for (const item of items) {
    if (item.role === "tool" && item.tool?.name === "result") {
      const callId = item.id.replace(/-result$/, "");
      const call = tools.get(callId);
      if (call?.tool) {
        call.tool.ok = item.tool.ok;
        if (item.tool.summary && call.tool.summary === call.tool.name) call.tool.summary = item.tool.summary;
        if (item.images) call.images = [...(call.images ?? []), ...item.images];
        continue;
      }
    }
    out.push(item);
  }
  return out;
}
