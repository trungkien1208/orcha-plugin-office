import { cleanUserText, parseClaudeTranscript } from "../src/conversation/claude.ts";
import { parseCodexTranscript } from "../src/conversation/codex.ts";
import { allowedHost, allowedOrigin, bearer, websocketToken } from "../src/http/guard.ts";
import { describe, expect, test } from "bun:test";
import fs from "node:fs";
import path from "node:path";

const fixtures = path.join(import.meta.dir, "fixtures");

describe("conversation parsers", () => {
  test("Claude lines become messages and one tool line, and skip thinking", () => {
    const items = parseClaudeTranscript(fs.readFileSync(path.join(fixtures, "claude-lines.ndjson"), "utf8"));
    expect(items.map((item) => item.role)).toEqual(["user", "agent", "tool", "agent"]);
    expect(items[2]?.tool).toEqual({ name: "Bash", summary: "bun test", ok: true });
    expect(items.some((item) => item.text?.includes("hidden"))).toBe(false);
    expect(items.some((item) => item.text?.includes("sidechain"))).toBe(false);
    const reply = items.find((item) => item.text?.includes("onerror"));
    expect(reply?.text).toContain("<img src=x onerror=alert(1)>");
    expect(reply?.images?.[0]?.mime).toBe("image/png");
  });

  test("Codex lines skip reasoning and fold the tool result", () => {
    const items = parseCodexTranscript(fs.readFileSync(path.join(fixtures, "codex-lines.ndjson"), "utf8"));
    expect(items.map((item) => `${item.role}:${item.tool?.name ?? item.text}`)).toEqual([
      "user:placeholder prompt",
      "agent:placeholder answer",
      "tool:shell",
      "tool:js",
    ]);
    expect(items[2]?.tool?.summary).toBe("ls");
    expect(items[2]?.tool?.ok).toBe(true);
  });

  test("a broken transcript line is skipped", () => {
    expect(parseClaudeTranscript("not json\n")).toEqual([]);
    expect(parseCodexTranscript("{")).toEqual([]);
  });
});

describe("local guard", () => {
  test("requires the per-run token and a local Host and Origin", () => {
    expect(bearer("Bearer abc", "abc")).toBe(true);
    expect(bearer(null, "abc")).toBe(false);
    expect(bearer("Bearer no", "abc")).toBe(false);
    expect(allowedHost("127.0.0.1:4317", 4317)).toBe(true);
    expect(allowedHost("evil.test:4317", 4317)).toBe(false);
    expect(allowedOrigin(null, ["http://127.0.0.1:4317"])).toBe(true);
    expect(allowedOrigin("http://127.0.0.1:4317", ["http://127.0.0.1:4317"])).toBe(true);
    expect(allowedOrigin("https://example.com", ["http://127.0.0.1:4317"])).toBe(false);
    expect(websocketToken("easy-job.abc", "abc")).toBe("easy-job.abc");
    expect(websocketToken("bearer", "abc")).toBeNull();
  });
});

describe("Claude Code wrappers in user lines", () => {
  test("show slash commands, shell runs and output the way the terminal does", () => {
    expect(cleanUserText("<command-message>model</command-message>\n<command-name>/model</command-name>\n<command-args>opus</command-args>")).toEqual({ role: "user", text: "/model opus" });
    expect(cleanUserText("<bash-input>ls -la</bash-input>")).toEqual({ role: "user", text: "! ls -la" });
    expect(cleanUserText("<local-command-stdout>Set model to Opus</local-command-stdout>")).toEqual({ role: "system", text: "Set model to Opus" });
    expect(cleanUserText("<bash-stdout></bash-stdout><bash-stderr></bash-stderr>")).toBeNull();
    expect(cleanUserText("[Request interrupted by user for tool use]")).toEqual({ role: "system", text: "Interrupted" });
  });
  test("drop reminders and caveats, keep real prompts", () => {
    expect(cleanUserText("<system-reminder>internal</system-reminder>")).toBeNull();
    expect(cleanUserText("Caveat: The messages below were generated by the user while running local commands. DO NOT respond.")).toBeNull();
    expect(cleanUserText("fix the bug <system-reminder>x</system-reminder>")).toEqual({ role: "user", text: "fix the bug" });
  });
});

describe("Codex and Cursor details", () => {
  test("Codex tool status comes from the exit code, not the word error", async () => {
    const { outputOf, parseCodexLine } = await import("../src/conversation/codex.ts");
    expect(outputOf("Exit code: 0\nWall time: 1s\nOutput:\nfound 3 errors in log").ok).toBe(true);
    expect(outputOf("Exit code: 2\nOutput:\nboom").ok).toBe(false);
    expect(outputOf(JSON.stringify({ output: "x", metadata: { exit_code: 1 } }))).toEqual({ text: "x", ok: false });
    expect(outputOf("").ok).toBe(true);
    const context = JSON.stringify({ type: "response_item", payload: { type: "message", role: "user", content: [{ type: "input_text", text: "<environment_context>\n<cwd>/x</cwd>\n</environment_context>" }] } });
    expect(parseCodexLine(context)).toEqual([]);
    const shell = JSON.stringify({ type: "response_item", payload: { type: "function_call", name: "shell", call_id: "c1", arguments: JSON.stringify({ command: ["bash", "-lc", "bun test\nmore"] }) } });
    expect(parseCodexLine(shell)[0]?.tool?.summary).toBe("bun test");
  });

  test("Cursor shows what you typed, its tool calls, and no 1970 clock", async () => {
    const { parseCursorLine, userQuery } = await import("../src/conversation/cursor.ts");
    expect(userQuery("<user_info>os</user_info>\n<user_query>\nfix it\n</user_query>")).toBe("fix it");
    const line = JSON.stringify({ role: "assistant", message: { content: [{ type: "text", text: "Running" }, { type: "tool_use", name: "Shell", input: { command: "ls" } }] } });
    const items = parseCursorLine(line);
    expect(items.map((item) => item.role)).toEqual(["agent", "tool"]);
    expect(items[0]?.at).toBe(0);
    expect(items[1]?.tool).toMatchObject({ name: "Shell", summary: "ls", ok: true });
  });

  test("Claude keeps images that come back in a tool result", () => {
    const png = "iVBORw0KGgo=";
    const raw = [
      JSON.stringify({ type: "assistant", uuid: "a", timestamp: "2026-10-30T05:00:00Z", message: { content: [{ type: "tool_use", id: "t1", name: "Read", input: { file_path: "/x.png" } }] } }),
      JSON.stringify({ type: "user", uuid: "u", timestamp: "2026-10-30T05:00:01Z", message: { content: [{ type: "tool_result", tool_use_id: "t1", content: [{ type: "image", source: { type: "base64", media_type: "image/png", data: png } }] }] } }),
    ].join("\n");
    const items = parseClaudeTranscript(raw);
    expect(items).toHaveLength(1);
    expect(items[0]?.images?.[0]?.dataUrl).toBe(`data:image/png;base64,${png}`);
    expect(items[0]?.tool?.ok).toBe(true);
  });
});
